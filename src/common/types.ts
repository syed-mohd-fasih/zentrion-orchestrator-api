/** Bookkeeping record for manifests that Zentrion has applied to the cluster. */
export interface AppliedManifest {
  id: string;
  kind: string;
  apiVersion: string;
  metadata: {
    name: string;
    namespace: string;
  };
  spec: any;
  appliedAt: string;
  appliedBy: string;
  status: 'active' | 'deleted';
}
