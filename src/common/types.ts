/** One turn in the AI assistant chat for a policy draft. */
export interface ChatMessage {
  role: 'user' | 'assistant';
  content: string;
  timestamp: string;
}

// ---------------------------------------------------------------------------
// Users / auth
// ---------------------------------------------------------------------------

/** Transport shape of a user (note: `password` is the stored bcrypt hash). */
export interface User {
  id: string;
  username: string;
  password: string; // bcrypt hash
  role: 'ADMIN' | 'ANALYST' | 'VIEWER';
  email: string;
  createdAt: string;
}

/** JWT payload embedded in issued access tokens. */
export interface JwtPayload {
  /** Subject — the user id. */
  sub: string;
  username: string;
  role: string;
}

